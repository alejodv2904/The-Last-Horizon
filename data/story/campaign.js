export const ACTS = [ACT_1, ACT_2, ACT_3, ACT_4, ACT_5, ACT_6, ACT_7, ACT_8];

/** Las 48 misiones en orden de campaña. */
export const MISSIONS = ACTS.flatMap((act) => act.missions);

/** Los 4 finales del Capítulo VI (viven dentro de la misión c6_06). */
export const ENDINGS = ACT_6.missions[5].endings;

const MISSION_BY_ID = new Map(MISSIONS.map((m) => [m.id, m]));

export function getMission(id) { return MISSION_BY_ID.get(id) || null; }
export function getAct(number) { return ACTS.find((a) => a.number === number) || null; }
export function getMissionsOfAct(number) { const a = getAct(number); return a ? a.missions : []; }
export function getNextMission(id) { const i = MISSIONS.findIndex((m) => m.id === id); return i >= 0 ? MISSIONS[i + 1] || null : null; }

/** Misiones cuyo `requires` ya está completado y que aún no se han completado. `completed` es un Set de ids. */
export function getAvailableMissions(completed) {
  return MISSIONS.filter((m) => !completed.has(m.id) && (m.requires === null || completed.has(m.requires)));
}

/**
 * Resuelve el final según el Honor acumulado y la decisión final.
 * @param {number} honor  Honor del jugador (-100..100)
 * @param {"protect_innocents"|"go_for_gold"} choice  Opción elegida en c6_06
 * @returns {object} uno de ENDINGS (dawn · gilded_shadow · debt_paid · ashes_gold)
 */
export function resolveEnding(honor, choice) {
  const high = honor >= CAMPAIGN_META.endingRules.highHonorMin;
  const id = choice === "protect_innocents" ? (high ? "dawn" : "debt_paid") : (high ? "gilded_shadow" : "ashes_gold");
  return ENDINGS[id];
}

/** ¿Se cumple la condición de una línea/objetivo? `flags` es un Set de banderas activas. */
export function passesCondition(entry, flags) {
  if (entry.onlyIf && !flags.has(entry.onlyIf)) return false;
  if (entry.unless && flags.has(entry.unless)) return false;
  return true;
}

export const CAMPAIGN = {
  meta: CAMPAIGN_META,
  npcs: NPCS,
  items: ITEMS,
  unlocks: UNLOCKS,
  locations: LOCATIONS,
  acts: ACTS,
  missions: MISSIONS,
  endings: ENDINGS,
};

export default CAMPAIGN;
